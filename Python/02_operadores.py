#Comenzamos con operaciones

first_number = 7.0
second_number = 5.0

#Los básicos de toda la vida

print(first_number+second_number)
print(first_number-second_number)
print(first_number*second_number)
print(first_number/second_number)

#Módulo, te da el resto

print(first_number%second_number)

#División floor, se redondea a un número entero

print(first_number//second_number)

#Calculamos exponente

print(first_number**second_number) #Sería 7^5
